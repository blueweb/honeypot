<?php

namespace Blueweb\NetteHoneypot;

use Nette\Forms\Container;
use Nette\Forms\Controls\BaseControl;
use Nette\Utils\Html;

class Honeypot extends BaseControl
{
	const MODE_CSS = "css";
	const MODE_JS = "js";

	/**
	 * @var bool
	 */
	private $inline;

	/**
	 * @var string
	 */
	private $nonce = '';

	/**
	 * @var string
	 */
	private $jsContent = <<<JS
(function(){elems=document.body.querySelectorAll('.bw-additional-data');for(var i=0;i<elems.length;++i){var elem=elems[i];elem.setAttribute('style', 'display:none !important;')}})();
JS;


	/**
	 * @var string
	 */
	private $cssContent = <<<CSS
.bw-additional-data{display:none !important;}
CSS;

	/**
	 * @var string
	 */
	private $mode;

	/**
	 * @var null|string
	 */
	private $message;

	/**
	 * @var array
	 */
	public $onError = [];

	public function __construct($caption = NULL, $message = NULL, $mode = self::MODE_JS, $inline = TRUE)
	{
		parent::__construct($caption);

		if (is_null($message)) {
			$message = "Please, don't fill this field";
		}

		$this->control->type = "text";
		$this->mode = $mode;
		$this->inline = $inline;
		$this->message = $message;

		$this->onError[] = function ($control) {
			$control->addError($this->message);
		};
	}

	public function getControl()
	{
		$control = parent::getControl();
		$label = parent::getLabel();

		$container = Html::el('div', [
			'id' => $control->id . '-container',
			'class' => 'bw-additional-data',
		]);
		$container->addHtml($label);
		$container->addHtml($control);

		// Try to auto-resolve CSP nonce from Nette's HttpResponse headers if not explicitly set
		if (!$this->nonce) {
			try {
				$presenter = $this->lookup('Nette\\Application\\UI\\Presenter', false);
				if ($presenter && method_exists($presenter, 'getHttpResponse')) {
					$resp = $presenter->getHttpResponse();
					$header = $resp->getHeader('Content-Security-Policy') ?: $resp->getHeader('Content-Security-Policy-Report-Only');
					if ($header && preg_match("#\\s'nonce-([\\w+/]+=*)'#", (string)$header, $m)) {
						$this->nonce = $m[1];
					}
				}
			} catch (\Throwable $e) {
				// ignore, nonce stays empty
			}
		}

		if ($this->inline) {
			if ($this->mode == self::MODE_JS) {
				$script = Html::el('script')
					->setType('text/javascript')
					->setHtml($this->jsContent);
				if ($this->nonce) {
					$script->setAttribute('nonce', $this->nonce);
				}
				$container->addHtml($script);
			} elseif ($this->mode == self::MODE_CSS) {
				$style = Html::el('style')
					->setText($this->cssContent);
				if ($this->nonce) {
					$style->setAttribute('nonce', $this->nonce);
				}
				$container->addHtml($style);
			}
		}

		return $container;
	}

	/**
	 * Sets CSP nonce to be added to inline <script> / <style> elements.
	 * Use the value generated by Nette (same one Latte uses for n:nonce).
	 *
	 * @param string|null $nonce
	 * @return self
	 */
	public function setNonce($nonce): self
	{
		$this->nonce = (string)$nonce;
		return $this;
	}

	public function getLabel($caption = NULL)
	{
		return NULL;
	}

	public function validate(): void
	{
		parent::validate();

		$value = $this->getValue();
		if (!empty($value)) {
			$this->onError($this);
		}
	}

	public static function register($inline = TRUE): void
	{
		Container::extensionMethod('addHoneypot', function ($container, $name, $caption = NULL, $message = NULL, $mode = self::MODE_JS) use ($inline) {
			return $container[$name] = new self($caption, $message, $mode, $inline);
		});
	}
}